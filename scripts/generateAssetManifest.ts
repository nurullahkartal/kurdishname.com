// scripts/generateAssetManifest.ts
// Reads dist/index.html (post-vite-build) and writes functions/_assetManifest.ts
// so the SSR worker injects the correct hashed asset URLs at runtime.

import fs from 'fs';
import path from 'path';

const distIndexPath = path.join(process.cwd(), 'dist', 'index.html');
if (!fs.existsSync(distIndexPath)) {
  console.error('❌ dist/index.html not found. Run `vite build` first.');
  process.exit(1);
}

const html = fs.readFileSync(distIndexPath, 'utf-8');

const scriptMatch = html.match(/<script[^>]*type="module"[^>]*src="[^"]+"[^>]*><\/script>/);
const mainScriptTag = scriptMatch ? scriptMatch[0] : '';

const styleMatch = html.match(/<link[^>]*rel="stylesheet"[^>]*href="[^"]+"[^>]*>/);
const mainStyleTag = styleMatch ? styleMatch[0] : '';

if (!mainScriptTag) {
  console.error('❌ Could not extract main script tag from dist/index.html');
  process.exit(1);
}

const content = `// AUTO-GENERATED by scripts/generateAssetManifest.ts at ${new Date().toISOString()}
// Do not edit manually — this file is regenerated on every \`npm run build\`.
export const MAIN_SCRIPT_TAG = ${JSON.stringify(mainScriptTag)};
export const MAIN_STYLE_TAG = ${JSON.stringify(mainStyleTag)};
`;

fs.writeFileSync(
  path.join(process.cwd(), 'functions', '_assetManifest.ts'),
  content,
  'utf-8'
);

console.log('✅ functions/_assetManifest.ts updated');
console.log('   Script:', mainScriptTag);
console.log('   Style: ', mainStyleTag);
